//! `cargo robocode battle`: compile robot files, run the battle, show it.

use std::path::{Path, PathBuf};
use std::process::Stdio;

use crate::Failure;
use crate::build_project::{cargo, robocode_source, write_project};

/// What to battle, from the command line.
pub struct BattleArgs {
    pub robot: String,
    pub vs: Vec<String>,
    pub arena: String,
    pub turns: u64,
    pub output: Option<PathBuf>,
    pub no_open: bool,
    pub verbose: bool,
    pub robocode_path: Option<PathBuf>,
}

/// One participant: a built-in robot or a robot file.
enum Entry {
    BuiltIn(String),
    File(PathBuf),
}

fn entry(arg: &str) -> Result<Entry, Failure> {
    if robocode::roster::BUILT_IN.contains(&arg) {
        return Ok(Entry::BuiltIn(arg.to_string()));
    }
    let path = Path::new(arg);
    if arg.ends_with(".rs") || path.exists() {
        return path
            .canonicalize()
            .map(Entry::File)
            .map_err(|_| Failure::usage(format!("robot file not found: {arg}")));
    }
    Err(Failure::usage(format!(
        "unknown opponent: {arg} (built-in robots: {}; or give a path to a .rs file)",
        robocode::roster::BUILT_IN.join(", ")
    )))
}

fn parse_arena(arena: &str) -> Result<(f64, f64), Failure> {
    let bad = || Failure::usage(format!("--arena must look like 800x600, got {arena}"));
    let (w, h) = arena.split_once(['x', 'X']).ok_or_else(bad)?;
    Ok((w.trim().parse().map_err(|_| bad())?, h.trim().parse().map_err(|_| bad())?))
}

/// The battle program: one module per distinct robot file.
fn battle_program(entries: &[Entry], files: &[PathBuf], width: f64, height: f64, turns: u64) -> String {
    let mut src = String::from("// Generated by cargo robocode. Do not edit.\n");
    for (k, file) in files.iter().enumerate() {
        src.push_str(&format!("#[path = {:?}]\nmod robot_{k};\n", file.display().to_string()));
    }
    src.push_str("\nfn main() {\n    let robots: Vec<Box<dyn robocode::api::Robot>> = vec![\n");
    for e in entries {
        match e {
            Entry::BuiltIn(name) => src.push_str(&format!("        robocode::roster::built_in({name:?}).unwrap(),\n")),
            Entry::File(path) => {
                let k = files.iter().position(|f| f == path).unwrap();
                src.push_str(&format!("        robot_{k}::__robocode_robot(),\n"));
            }
        }
    }
    src.push_str(&format!(
        "    ];\n\
         \x20   let config = robocode::physics::BattleConfig {{ battlefield: robocode::Battlefield::new({width:?}, {height:?}), ..Default::default() }};\n\
         \x20   let battle = robocode::runner::Battle::new(config, &robocode::roster::spawns({n}, {width:?}, {height:?}), robots);\n\
         \x20   let recorded = robocode::recording::record_with_summary(battle, {turns});\n\
         \x20   let out = std::env::args().nth(1).expect(\"output path\");\n\
         \x20   std::fs::write(out, &recorded.json).expect(\"write recording\");\n\
         \x20   println!(\"{{}}\", recorded.summary());\n\
         }}\n",
        n = entries.len()
    ));
    src
}

/// Compiles and runs the battle; returns the recording JSON.
pub fn run(args: &BattleArgs) -> Result<String, Failure> {
    let mut entries = vec![entry(&args.robot)?];
    let vs = if args.vs.is_empty() { vec!["SittingDuck".to_string()] } else { args.vs.clone() };
    for v in &vs {
        entries.push(entry(v)?);
    }
    let (width, height) = parse_arena(&args.arena)?;
    robocode::recording::validate_setup(entries.len(), width, height, args.turns).map_err(Failure::usage)?;
    let source = robocode_source(args.robocode_path.as_deref())?;

    let mut files: Vec<PathBuf> = Vec::new();
    for e in &entries {
        if let Entry::File(p) = e
            && !files.contains(p)
        {
            files.push(p.clone());
        }
    }
    let program = battle_program(&entries, &files, width, height, args.turns);
    let project = write_project("battle", &program, "main.rs", "", &source)?;

    eprintln!("Compiling robots…");
    let build = cargo(&project, &["build", "--release", "--color", "never"])
        .stdout(Stdio::null())
        .stderr(Stdio::piped())
        .output()
        .map_err(|e| Failure::usage(format!("could not run cargo: {e}")))?;
    let build_log = String::from_utf8_lossy(&build.stderr);
    if args.verbose || !build.status.success() {
        eprint!("{build_log}");
    }
    if !build.status.success() {
        if build_log.contains("__robocode_robot") {
            for f in &files {
                eprintln!("hint: add robocode::robot!(YourRobot); to {}", f.display());
            }
        }
        return Err(Failure { code: 1, message: "your robot did not compile (see the errors above)".into() });
    }

    let exe = project.target_dir.join("release").join(format!("{}{}", project.package, std::env::consts::EXE_SUFFIX));
    let recording_path = project.dir.join("battle.json");
    let ran = std::process::Command::new(&exe)
        .arg(&recording_path)
        .stderr(Stdio::inherit())
        .output()
        .map_err(|e| Failure::usage(format!("could not run the battle: {e}")))?;
    if !ran.status.success() {
        return Err(Failure { code: 1, message: "the battle crashed (a robot panicked; see above)".into() });
    }
    print!("{}", String::from_utf8_lossy(&ran.stdout));
    let json = std::fs::read_to_string(&recording_path)
        .map_err(|e| Failure::usage(format!("could not read the recording: {e}")))?;
    if let Some(out) = &args.output {
        std::fs::write(out, &json).map_err(|e| Failure::usage(format!("could not write {}: {e}", out.display())))?;
        eprintln!("Saved the recording to {}", out.display());
    }
    Ok(json)
}
