//! `cargo robocode battle`: compile robot files, run the battle, show it.

use std::path::{Path, PathBuf};
use std::process::Stdio;

use crate::Failure;
use crate::build_project::{cargo, robocode_source, write_project};

/// What to battle, from the command line.
pub struct BattleArgs {
    pub robot: String,
    pub vs: Vec<String>,
    pub arena: String,
    pub turns: u64,
    pub rounds: u32,
    /// Run live (paced, streamed) instead of precomputing.
    pub live: bool,
    pub output: Option<PathBuf>,
    pub verbose: bool,
    pub robocode_path: Option<PathBuf>,
}

/// One participant: a built-in robot or a robot file.
enum Entry {
    BuiltIn(String),
    File(PathBuf),
}

fn entry(arg: &str) -> Result<Entry, Failure> {
    if robocode::roster::BUILT_IN.contains(&arg) {
        return Ok(Entry::BuiltIn(arg.to_string()));
    }
    let path = Path::new(arg);
    if arg.ends_with(".rs") || path.exists() {
        return path
            .canonicalize()
            .map(Entry::File)
            .map_err(|_| Failure::usage(format!("robot file not found: {arg}")));
    }
    Err(Failure::usage(format!(
        "unknown opponent: {arg} (built-in robots: {}; or give a path to a .rs file)",
        robocode::roster::BUILT_IN.join(", ")
    )))
}

fn parse_arena(arena: &str) -> Result<(f64, f64), Failure> {
    let bad = || Failure::usage(format!("--arena must look like 800x600, got {arena}"));
    let (w, h) = arena.split_once(['x', 'X']).ok_or_else(bad)?;
    Ok((w.trim().parse().map_err(|_| bad())?, h.trim().parse().map_err(|_| bad())?))
}

/// The battle program: one module per distinct robot file. It records
/// round 1 and, for several rounds, plays them all and prints the totals.
fn battle_program(entries: &[Entry], files: &[PathBuf], width: f64, height: f64, turns: u64, rounds: u32) -> String {
    let mut src = String::from("// Generated by cargo robocode. Do not edit.\n");
    for (k, file) in files.iter().enumerate() {
        src.push_str(&format!("#[path = {:?}]\nmod robot_{k};\n", file.display().to_string()));
    }
    src.push_str("\nfn make_battle() -> robocode::runner::Battle {\n    let robots: Vec<Box<dyn robocode::api::Robot>> = vec![\n");
    for e in entries {
        match e {
            Entry::BuiltIn(name) => src.push_str(&format!("        robocode::roster::built_in({name:?}).unwrap(),\n")),
            Entry::File(path) => {
                let k = files.iter().position(|f| f == path).unwrap();
                src.push_str(&format!("        robot_{k}::__robocode_robot(),\n"));
            }
        }
    }
    src.push_str(&format!(
        "    ];\n\
         \x20   let config = robocode::physics::BattleConfig {{ battlefield: robocode::Battlefield::new({width:?}, {height:?}), ..Default::default() }};\n\
         \x20   robocode::runner::Battle::new(config, &robocode::roster::spawns({n}, {width:?}, {height:?}), robots)\n\
         }}\n\n\
         fn main() {{\n\
         \x20   let args: Vec<String> = std::env::args().collect();\n\
         \x20   let out = args.get(1).expect(\"output path\").clone();\n\
         \x20   if args.get(2).map(String::as_str) == Some(\"--live\") {{\n\
         \x20       live(&out, args.get(3).and_then(|t| t.parse::<u32>().ok()));\n\
         \x20       return;\n\
         \x20   }}\n\
         \x20   let recorded = robocode::recording::record_with_summary(make_battle(), {turns});\n\
         \x20   std::fs::write(out, &recorded.json).expect(\"write recording\");\n\
         \x20   if {rounds} <= 1 {{\n\
         \x20       println!(\"{{}}\", recorded.summary());\n\
         \x20       return;\n\
         \x20   }}\n\
         \x20   let mut battle = make_battle();\n\
         \x20   let results = battle.run_rounds({rounds}, {turns});\n\
         \x20   for (r, o) in results.rounds.iter().enumerate() {{\n\
         \x20       let w = o.winner.map_or(\"no winner\".to_string(), |i| battle.name(i).to_string());\n\
         \x20       println!(\"Round {{}}: {{}} after {{}} turns\", r + 1, w, o.turns);\n\
         \x20   }}\n\
         \x20   let wins: Vec<String> = (0..results.wins.len()).map(|i| format!(\"{{}} {{}}\", battle.name(i), results.wins[i])).collect();\n\
         \x20   println!(\"Wins: {{}}\", wins.join(\", \"));\n\
         \x20   let damage: Vec<String> = (0..results.bullet_damage.len()).map(|i| format!(\"{{}} {{:.0}}\", battle.name(i), results.bullet_damage[i])).collect();\n\
         \x20   println!(\"Bullet damage: {{}}\", damage.join(\", \"));\n\
         \x20   let score: Vec<String> = (0..results.scores.len()).map(|i| format!(\"{{}} {{:.0}}\", battle.name(i), results.scores[i].total())).collect();\n\
         \x20   println!(\"Score: {{}}\", score.join(\", \"));\n\
         }}\n\n\
         /// Live mode: one JSON line per turn on stdout, paced; commands on stdin.\n\
         fn live(out: &str, tps: Option<u32>) {{\n\
         \x20   use std::io::{{BufRead, Write}};\n\
         \x20   let (tx, rx) = std::sync::mpsc::channel::<String>();\n\
         \x20   std::thread::spawn(move || {{\n\
         \x20       for line in std::io::stdin().lock().lines() {{\n\
         \x20           let Ok(line) = line else {{ break }};\n\
         \x20           if tx.send(line).is_err() {{ break; }}\n\
         \x20       }}\n\
         \x20   }});\n\
         \x20   let mut session = robocode::live::LiveSession::new(make_battle(), {turns});\n\
         \x20   let mut pacer = robocode::live::Pacer::new(tps);\n\
         \x20   let start = std::time::Instant::now();\n\
         \x20   let now = || start.elapsed().as_nanos() as u64;\n\
         \x20   let mut o = std::io::stdout().lock();\n\
         \x20   writeln!(o, \"{{}}\", session.header()).unwrap();\n\
         \x20   writeln!(o, \"{{}}\", session.initial_frame().to_json()).unwrap();\n\
         \x20   o.flush().unwrap();\n\
         \x20   while !session.finished() {{\n\
         \x20       while let Ok(cmd) = rx.try_recv() {{\n\
         \x20           match cmd.trim() {{\n\
         \x20               \"pause\" => pacer.pause(),\n\
         \x20               \"resume\" => pacer.resume(now()),\n\
         \x20               \"step\" => pacer.request_step(),\n\
         \x20               c => if let Some(v) = c.strip_prefix(\"tps \") {{ pacer.set_tps(v.parse().ok(), now()); }},\n\
         \x20           }}\n\
         \x20       }}\n\
         \x20       for _ in 0..pacer.due(now()) {{\n\
         \x20           match session.step() {{\n\
         \x20               Some(frame) => writeln!(o, \"{{}}\", frame.to_json()).unwrap(),\n\
         \x20               None => break,\n\
         \x20           }}\n\
         \x20       }}\n\
         \x20       o.flush().unwrap();\n\
         \x20       std::thread::sleep(std::time::Duration::from_millis(2));\n\
         \x20   }}\n\
         \x20   std::fs::write(out, session.recording()).expect(\"write recording\");\n\
         \x20   writeln!(o, \"{{{{\\\"done\\\":true}}}}\").unwrap();\n\
         \x20   o.flush().unwrap();\n\
         }}\n",
        n = entries.len()
    ));
    src
}

/// The compiled battle program and where it writes its recording.
pub struct Compiled {
    pub exe: PathBuf,
    pub recording_path: PathBuf,
}

/// Compiles the robots into a battle program.
pub fn compile(args: &BattleArgs) -> Result<Compiled, Failure> {
    let mut entries = vec![entry(&args.robot)?];
    let vs = if args.vs.is_empty() { vec!["SittingDuck".to_string()] } else { args.vs.clone() };
    for v in &vs {
        entries.push(entry(v)?);
    }
    let (width, height) = parse_arena(&args.arena)?;
    robocode::recording::validate_setup(entries.len(), width, height, args.turns).map_err(Failure::usage)?;
    if !(1..=100).contains(&args.rounds) {
        return Err(Failure::usage(format!("--rounds must be 1..=100, got {}", args.rounds)));
    }
    if args.live && args.rounds > 1 {
        return Err(Failure::usage("--live plays one round; drop --rounds (or run without --live)"));
    }
    let source = robocode_source(args.robocode_path.as_deref())?;

    let mut files: Vec<PathBuf> = Vec::new();
    for e in &entries {
        if let Entry::File(p) = e
            && !files.contains(p)
        {
            files.push(p.clone());
        }
    }
    let program = battle_program(&entries, &files, width, height, args.turns, args.rounds);
    let project = write_project("battle", &[("main.rs", &program)], &[], "", &source)?;

    eprintln!("Compiling robots…");
    let build = cargo(&project, &["build", "--release", "--color", "never"])
        .stdout(Stdio::null())
        .stderr(Stdio::piped())
        .output()
        .map_err(|e| Failure::usage(format!("could not run cargo: {e}")))?;
    let build_log = String::from_utf8_lossy(&build.stderr);
    if args.verbose || !build.status.success() {
        eprint!("{build_log}");
    }
    if !build.status.success() {
        if build_log.contains("__robocode_robot") {
            for f in &files {
                eprintln!("hint: add robocode::robot!(YourRobot); to {}", f.display());
            }
        }
        return Err(Failure { code: 1, message: "your robot did not compile (see the errors above)".into() });
    }

    let exe = project.target_dir.join("release").join(format!("{}{}", project.package, std::env::consts::EXE_SUFFIX));
    Ok(Compiled { exe, recording_path: project.dir.join("battle.json") })
}

/// Compiles and runs the battle to completion; returns the recording JSON.
pub fn run(args: &BattleArgs) -> Result<String, Failure> {
    let Compiled { exe, recording_path } = compile(args)?;
    let ran = std::process::Command::new(&exe)
        .arg(&recording_path)
        .stderr(Stdio::inherit())
        .output()
        .map_err(|e| Failure::usage(format!("could not run the battle: {e}")))?;
    if !ran.status.success() {
        return Err(Failure { code: 1, message: "the battle crashed (a robot panicked; see above)".into() });
    }
    print!("{}", String::from_utf8_lossy(&ran.stdout));
    let json = std::fs::read_to_string(&recording_path)
        .map_err(|e| Failure::usage(format!("could not read the recording: {e}")))?;
    if let Some(out) = &args.output {
        std::fs::write(out, &json).map_err(|e| Failure::usage(format!("could not write {}: {e}", out.display())))?;
        eprintln!("Saved the recording to {}", out.display());
    }
    Ok(json)
}

/// Starts the battle program in live mode: frames on its stdout, commands on its stdin.
pub fn spawn_live(compiled: &Compiled, tps: Option<u32>) -> Result<std::process::Child, Failure> {
    let _ = std::fs::remove_file(&compiled.recording_path);
    std::process::Command::new(&compiled.exe)
        .arg(&compiled.recording_path)
        .arg("--live")
        .arg(tps.map_or_else(|| "max".to_string(), |t| t.to_string()))
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .stderr(Stdio::inherit())
        .spawn()
        .map_err(|e| Failure::usage(format!("could not start the battle: {e}")))
}
