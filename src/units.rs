//! Fixed-point integer quantities used by strategies.
//!
//! Strategies see and act in these units in every build, so the `decide`
//! function that Verus proves is the same code that runs in battles.
//!
//! | Quantity | Type | Unit |
//! |---|---|---|
//! | energy, gun heat, bullet power | [`Energy`], [`GunHeat`], [`Power`] | milli-units (×1000) |
//! | angles | [`Angle`] | decidegrees (×10), absolute angles in `0..3600` |
//!
//! Conversions from the `f64` engine round in the *safe* direction: energy
//! rounds down and gun heat rounds up, so a strategy never believes it has
//! more energy, or a cooler gun, than the engine had at the start of the turn.
//! Energy lost later in the same turn (for example hitting a wall during
//! movement, which the engine runs before firing) is not covered.

#[cfg(feature = "verus")]
use vstd::prelude::*;

/// Robot energy in milli-units.
#[cfg_attr(feature = "verus", verus_verify)]
#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord)]
pub struct Energy(pub u32);

/// Gun heat in milli-units. The gun can fire only at `GunHeat(0)`.
#[cfg_attr(feature = "verus", verus_verify)]
#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord)]
pub struct GunHeat(pub u32);

/// Bullet power in milli-units. Legal range: [`MIN_POWER`]..=[`MAX_POWER`].
#[cfg_attr(feature = "verus", verus_verify)]
#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord)]
pub struct Power(pub u32);

/// An absolute angle in decidegrees, `0..3600`. 0 points up, angles grow clockwise.
#[cfg_attr(feature = "verus", verus_verify)]
#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord)]
pub struct Angle(pub i32);

/// Smallest legal bullet power (0.1).
pub const MIN_POWER: Power = Power(100);
/// Largest legal bullet power (3.0).
pub const MAX_POWER: Power = Power(3000);
/// Gun heat removed per turn (0.1).
pub const GUN_COOLING: GunHeat = GunHeat(100);

impl Energy {
    /// Converts engine energy, rounding **down** and clamping at 0.
    pub fn from_f64(energy: f64) -> Energy {
        Energy((energy * 1000.0).floor().max(0.0) as u32)
    }
}

impl GunHeat {
    /// Converts engine gun heat, rounding **up** and clamping at 0.
    ///
    /// Float residue such as `1e-16` becomes `GunHeat(1)`, because the engine
    /// still treats that gun as hot.
    pub fn from_f64(heat: f64) -> GunHeat {
        GunHeat((heat * 1000.0).ceil().max(0.0) as u32)
    }
}

impl Power {
    /// Power as the engine's `f64`.
    pub fn to_f64(self) -> f64 {
        self.0 as f64 / 1000.0
    }
}

impl Angle {
    /// Converts degrees to decidegrees, rounding to nearest and normalizing to `0..3600`.
    pub fn from_degrees(degrees: f64) -> Angle {
        Angle(((degrees * 10.0).round() as i32).rem_euclid(3600))
    }

    /// The angle in degrees.
    pub fn to_degrees(self) -> f64 {
        self.0 as f64 / 10.0
    }
}

#[cfg(feature = "verus")]
verus! {
/// Specification of [`angle_diff`]: the signed shortest turn from `from` to `to`.
pub open spec fn spec_angle_diff(to: int, from: int) -> int {
    let d = to - from;
    if d > 1800 { d - 3600 } else if d <= -1800 { d + 3600 } else { d }
}
}

/// The signed shortest turn from `from` to `to`, in decidegrees, within `(-1800, 1800]`.
/// Positive means turn right (clockwise).
#[cfg_attr(feature = "verus", verus_verify)]
#[cfg_attr(feature = "verus", verus_spec(r =>
    requires
        0 <= to.0 < 3600,
        0 <= from.0 < 3600,
    ensures
        r == spec_angle_diff(to.0 as int, from.0 as int),
        -1800 < r <= 1800,
        from.0 + r == to.0 || from.0 + r == to.0 + 3600 || from.0 + r == to.0 - 3600,
))]
pub fn angle_diff(to: Angle, from: Angle) -> i32 {
    let d = to.0 - from.0;
    if d > 1800 {
        d - 3600
    } else if d <= -1800 {
        d + 3600
    } else {
        d
    }
}

/// Damage a bullet deals to the robot it hits: `4p + 2·max(p − 1, 0)`.
#[cfg_attr(feature = "verus", verus_verify)]
#[cfg_attr(feature = "verus", verus_spec(r =>
    requires p.0 <= 3000,
    ensures
        p.0 >= 100 ==> r.0 > 0,
        r.0 <= 16000,
))]
pub fn bullet_damage(p: Power) -> Energy {
    let extra = if p.0 > 1000 { 2 * (p.0 - 1000) } else { 0 };
    Energy(4 * p.0 + extra)
}

/// Energy returned to the shooter when its bullet hits: `3p`.
#[cfg_attr(feature = "verus", verus_verify)]
#[cfg_attr(feature = "verus", verus_spec(r =>
    requires p.0 <= 3000,
    ensures r.0 == 3 * p.0,
))]
pub fn bullet_hit_bonus(p: Power) -> Energy {
    Energy(3 * p.0)
}

/// Gun heat generated by firing: `1 + p / 5`.
#[cfg_attr(feature = "verus", verus_verify)]
#[cfg_attr(feature = "verus", verus_spec(r =>
    requires p.0 <= 3000,
    ensures r.0 >= 1000 && r.0 <= 1600,
))]
pub fn gun_heat_for_power(p: Power) -> GunHeat {
    GunHeat(1000 + p.0 / 5)
}
